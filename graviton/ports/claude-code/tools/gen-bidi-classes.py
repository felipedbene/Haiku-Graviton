#!/usr/bin/env python3
"""Convert Unicode's DerivedBidiClass.txt into compat/lib/bidi-classes.mjs.

  gen-bidi-classes.py <DerivedBidiClass.txt> > compat/lib/bidi-classes.mjs

Input: https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedBidiClass.txt
(the same Unicode version as width-tables.mjs). Every code point gets its
derived class: the @missing defaults first (in file order, later lines
override), then the explicit data lines. The output is a sorted list of
maximal ranges, base64 of little-endian u32 triples (start, end, class).
"""
import base64, hashlib, re, struct, sys

ABBR = {"Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Terminator": "ET",
	"Boundary_Neutral": "BN"}
CLASSES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
	"LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]

def main(path):
	raw = open(path, "rb").read()
	text = raw.decode("utf-8")
	first = text.splitlines()[0].strip("# ")
	cls = bytearray(0x110000)	# index into CLASSES; 0 = L
	for m in re.finditer(r"^# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)", text, re.M):
		a, b, name = int(m[1], 16), int(m[2], 16), ABBR[m[3]]
		cls[a:b + 1] = bytes([CLASSES.index(name)]) * (b - a + 1)
	for line in text.splitlines():
		line = line.split("#")[0].strip()
		if not line:
			continue
		cps, name = [x.strip() for x in line.split(";")]
		a, _, b = cps.partition("..")
		a = int(a, 16); b = int(b, 16) if b else a
		cls[a:b + 1] = bytes([CLASSES.index(name)]) * (b - a + 1)
	out, start = [], 0
	for cp in range(1, 0x110001):
		if cp == 0x110000 or cls[cp] != cls[start]:
			if cls[start] != 0:
				out.append(struct.pack("<III", start, cp - 1, cls[start]))
			start = cp
	blob = base64.b64encode(b"".join(out)).decode()
	print("// GENERATED by tools/gen-bidi-classes.py from Unicode %s" % first)
	print("// (sha256 %s). Do not edit." % hashlib.sha256(raw).hexdigest())
	print("export const BIDI_CLASS_NAMES = %s;" % ("[" + ", ".join('"%s"' % c for c in CLASSES) + "]"))
	print("const u8 = Uint8Array.from(atob(\"%s\"), (c) => c.charCodeAt(0));" % blob)
	print("const R = new Uint32Array(u8.buffer);	// start, end, class; code points not covered are L")
	print("""export function bidiClass(cp) {
	let lo = 0, hi = R.length / 3 - 1;
	while (lo <= hi) {
		const mid = (lo + hi) >> 1, s = R[3 * mid], e = R[3 * mid + 1];
		if (cp < s) hi = mid - 1;
		else if (cp > e) lo = mid + 1;
		else return BIDI_CLASS_NAMES[R[3 * mid + 2]];
	}
	return "L";
}""")

main(sys.argv[1])
