#!/usr/bin/env python3
"""Convert Bun's generated stringWidthTables.h into compat/lib/width-tables.mjs.

  gen-width-tables.py <stringWidthTables.h> > compat/lib/width-tables.mjs

Input: oven-sh/bun tag bun-v1.4.4 (38afee6c84fc), src/jsc/bindings/stringWidthTables.h,
sha256 543732f51e1308e4e1c115b164a415abd399a5d0ec7d971a48ae5cb6dae71b8f -- itself
generated from the Unicode 17.0.0 UCD. The arrays are copied value for value (as
base64 of their little-endian bytes); nothing is recomputed, so the JS lookup is the
same data Bun's C++ indexes.
"""
import base64, hashlib, re, struct, sys

PINNED = "543732f51e1308e4e1c115b164a415abd399a5d0ec7d971a48ae5cb6dae71b8f"
raw = open(sys.argv[1], "rb").read()
if hashlib.sha256(raw).hexdigest() != PINNED:
	sys.exit("gen-width-tables: input sha256 is not the pinned bun-v1.4.4 header")
text = raw.decode()
out = []
for name, ctype, n in (("kGraphemeBreakStage1", "uint16_t", 8192), ("kGraphemeBreakStage2", "uint8_t", 32768),
		("kGraphemeBreakStage3", "uint8_t", 33)):
	m = re.search(r"static constexpr %s %s\[%d\] = \{(.*?)\};" % (ctype, name, n), text, re.S)
	if not m:
		sys.exit("gen-width-tables: %s not found with the expected type/size" % name)
	vals = [int(v, 0) for v in m.group(1).replace("\n", " ").split(",") if v.strip()]
	if len(vals) != n:
		sys.exit("gen-width-tables: %s has %d values, expected %d" % (name, len(vals), n))
	fmt, js = ("<%dH" % n, "Uint16Array") if ctype == "uint16_t" else ("<%dB" % n, "Uint8Array")
	b64 = base64.b64encode(struct.pack(fmt, *vals)).decode()
	out.append((name, js, n, b64))
print("// GENERATED by tools/gen-width-tables.py from Bun bun-v1.4.4")
print("// src/jsc/bindings/stringWidthTables.h (sha256 %s; Unicode 17.0.0). Do not edit." % PINNED)
print('const dec = (b64, T, n) => { const u8 = Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));')
print('\tconst a = new T(u8.buffer, 0, n); return a; };')
for name, js, n, b64 in out:
	print('export const %s = dec("%s", %s, %d);' % (name, b64, js, n))
